"""
Модуль сохранения регистра слова при исправлении.

Логика:
1. Если исходное слово ВСЕ ЗАГЛАВНЫЕ -> предложение тоже в ВЕРХНИЙ регистр.
2. Если исходное слово С Заглавной Буквы -> предложение с Заглавной.
3. Иначе (все строчные) -> предложение как есть (обычно корректор отдает строчное).
"""

def apply_casing(original: str, suggestion: str) -> str:
    """
    Применяет регистр оригинального слова к предложенной замене.
    
    Args:
        original: Исходное слово (с опечаткой).
        suggestion: Слово-кандидат на замену от корректора.
    
    Returns:
        suggestion с примененным регистром original.
    """
    if not original or not suggestion:
        return suggestion

    # Случай 1: Все буквы заглавные (например, "ПРИВЕТ" -> "ПРИВЕТ")
    # Проверяем, есть ли хотя бы одна буква и все ли они верхнего регистра
    if original.isupper():
        return suggestion.upper()
    
    # Случай 2: Первая буква заглавная (например, "Привет" -> "Привет")
    if original[0].isupper():
        if len(suggestion) == 1:
            return suggestion.upper()
        return suggestion[0].upper() + suggestion[1:].lower()
    
    # Случай 3: Все строчные или нет букв -> оставляем suggestion как есть
    # (корректор обычно отдаёт нижний регистр, но может вернуть и другой)
    return suggestion
